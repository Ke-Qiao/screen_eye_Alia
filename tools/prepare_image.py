#!/usr/bin/env python3
"""Convert the supplied artwork to an embedded RGB565 asset; never generate artwork."""
import argparse
from array import array
from pathlib import Path
import sys

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]


def rgb565(image):
    data = image.convert('RGB').tobytes()
    pixels = array('H', (((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
                         for r, g, b in zip(data[0::3], data[1::3], data[2::3])))
    if sys.byteorder != 'little':
        pixels.byteswap()
    return pixels.tobytes()


def panel_texture(image):
    """Replace exterior matte and feather only the outer rim onto native white."""
    image = image.convert('RGB')
    width, height = image.size
    pixels = image.load()
    background = set()
    pending = [(x, y) for x in range(width) for y in (0, height - 1)]
    pending += [(x, y) for y in range(height) for x in (0, width - 1)]
    while pending:
        x, y = pending.pop()
        # shortcut: this artwork's dark outline stops the fill; use an alpha mask if the artwork changes.
        if (x, y) in background or min(pixels[x, y]) < 8:
            continue
        background.add((x, y))
        for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
            if 0 <= nx < width and 0 <= ny < height:
                pending.append((nx, ny))
    coverage = Image.new('L', image.size, 255)
    for position in background:
        coverage.putpixel(position, 0)
    # Clear isolated rim pixels, then soften the one-pixel inset; the interior stays opaque.
    coverage = coverage.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(.6))
    for position in background:
        coverage.putpixel(position, 0)  # No old white matte may bleed back from outside.
    return rgb565(Image.composite(image, Image.new('RGB', image.size), coverage))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'assets/eye-source.png')
    parser.add_argument('--crop', type=int, nargs=4, default=(512, 120, 1024, 896),
                        metavar=('LEFT', 'TOP', 'RIGHT', 'BOTTOM'), help='Trim blank margins; coordinates in the original image')
    parser.add_argument('--rotation', type=int, choices=(0, 90, 180, 270), default=0, help='Clockwise degrees (default: 0 for portrait mounting)')
    parser.add_argument('--max-size', type=int, nargs=2, default=(344, 228), metavar=('WIDTH', 'HEIGHT'), help='Size limit before rotation')
    args = parser.parse_args()
    if any(size < 1 or size > 4096 for size in args.max_size):
        parser.error('--max-size must be between 1 and 4096')
    with Image.open(args.source) as source:
        left, top, right, bottom = args.crop
        if not (0 <= left < right <= source.width and 0 <= top < bottom <= source.height):
            parser.error('--crop must be inside the source image')
        image = source.convert('RGB').crop(args.crop)
        image.thumbnail(tuple(args.max_size), Image.Resampling.LANCZOS)
        image = image.rotate(-args.rotation, expand=True)
    data = ROOT / 'firmware/data/eye.rgb565'
    data.parent.mkdir(parents=True, exist_ok=True)
    data.write_bytes(panel_texture(image))
    (ROOT / 'firmware/include/eye_asset.h').write_text(
        '// Generated by tools/prepare_image.py. Source artwork is in assets/eye-source.png.\n'
        '#pragma once\n'
        f'constexpr int kTextureWidth = {image.width};\n'
        f'constexpr int kTextureHeight = {image.height};\n', encoding='utf-8')
    (ROOT / 'assets').mkdir(exist_ok=True)
    image.save(ROOT / 'assets/eye-texture.png')
    print(f'{image.width} x {image.height}, {data.stat().st_size} bytes, RGB565 little-endian, clockwise {args.rotation} degrees')


if __name__ == '__main__':
    main()
